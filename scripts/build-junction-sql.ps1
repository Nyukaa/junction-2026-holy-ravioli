<#
.SYNOPSIS
  Builds SQL scripts that create the `junction` schema and load the S-Bank synthetic CSVs into it.

.DESCRIPTION
  Reads the dataset CSVs and writes, into -OutDir:
    00_schema.sql      copy of db/migrations/001_junction_schema.sql
    01_cust.sql        COPY data for junction.cust
    02_tx.sql          COPY data for junction.tx (large, ~3.6M rows)
    03_mtg_link.sql    COPY data for junction.mtg_link
    04_mtg_events.sql  COPY data for junction.mtg_events
    load_all.sql       runs everything above (truncates first, so it can be re-run)

  SAS style timestamps (e.g. 03OCT24:09:04:04) are converted to ISO (2024-10-03 09:04:04).
  Empty CSV fields become NULL. The output uses `COPY ... FROM STDIN`, so run it with psql:

    psql "$env:DATABASE_URL" -v ON_ERROR_STOP=1 -f db/seed/load_all.sql

  The output contains the raw dataset; it is git-ignored and must not be committed.

.EXAMPLE
  ./scripts/build-junction-sql.ps1 -SourceDir C:\code\Junction-2026-S-pankki
#>
[CmdletBinding()]
param(
    [string]$SourceDir = 'C:\code\Junction-2026-S-pankki',
    [string]$OutDir = (Join-Path $PSScriptRoot '..\db\seed'),
    # Rows per COPY block. Each block commits on its own, which keeps WAL small on a small Aiven plan.
    [int]$ChunkRows = 200000
)

$ErrorActionPreference = 'Stop'
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)

$months = @{
    JAN = '01'; FEB = '02'; MAR = '03'; APR = '04'; MAY = '05'; JUN = '06'
    JUL = '07'; AUG = '08'; SEP = '09'; OCT = '10'; NOV = '11'; DEC = '12'
}

# 03OCT24:09:04:04 -> 2024-10-03 09:04:04
function Convert-SasTimestamp([string]$value) {
    if ($value.Length -ne 16 -or $value[7] -ne ':') { throw "Unexpected timestamp format: '$value'" }
    $month = $months[$value.Substring(2, 3)]
    if (-not $month) { throw "Unknown month in timestamp: '$value'" }
    return '20' + $value.Substring(5, 2) + '-' + $month + '-' + $value.Substring(0, 2) + ' ' + $value.Substring(8)
}

# Writes one `COPY ... FROM STDIN` block. Fields before $TimestampIndex must not be quoted (true for this dataset).
function Write-CopyFile {
    param(
        [string]$CsvName,
        [string]$Table,
        [string[]]$Columns,
        [int]$TimestampIndex = -1,
        [string]$OutFile
    )
    $csvPath = Join-Path $SourceDir $CsvName
    if (-not (Test-Path $csvPath)) { throw "Missing file: $csvPath" }

    $reader = New-Object System.IO.StreamReader($csvPath, [System.Text.Encoding]::UTF8, $true)
    $writer = New-Object System.IO.StreamWriter($OutFile, $false, $utf8NoBom, 1MB)
    $writer.NewLine = "`n"
    $rows = 0
    try {
        $header = $reader.ReadLine()
        if ($header.StartsWith('version https://git-lfs')) { throw "$CsvName is a Git LFS pointer, download the real file." }
        $copyHeader = "COPY $Table ($($Columns -join ', ')) FROM STDIN WITH (FORMAT csv);"
        $writer.WriteLine("-- Generated by scripts/build-junction-sql.ps1 from $CsvName. Do not commit.")
        $writer.WriteLine($copyHeader)

        while ($null -ne ($line = $reader.ReadLine())) {
            if ($line.Length -eq 0) { continue }
            if ($rows -gt 0 -and $rows % $ChunkRows -eq 0) {
                $writer.WriteLine('\.')
                $writer.WriteLine($copyHeader)
            }
            if ($TimestampIndex -ge 0) {
                $start = 0
                for ($i = 0; $i -lt $TimestampIndex; $i++) { $start = $line.IndexOf(',', $start) + 1 }
                $end = $line.IndexOf(',', $start)
                if ($end -lt 0) { $end = $line.Length }
                $ts = Convert-SasTimestamp $line.Substring($start, $end - $start)
                $line = $line.Substring(0, $start) + $ts + $line.Substring($end)
            }
            $writer.WriteLine($line)
            $rows++
        }
        $writer.WriteLine('\.')
    }
    finally {
        $reader.Dispose()
        $writer.Dispose()
    }
    Write-Host ("{0,-18} {1,10:N0} rows -> {2}" -f $Table, $rows, $OutFile)
}

New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
$OutDir = (Resolve-Path $OutDir).Path
$sw = [System.Diagnostics.Stopwatch]::StartNew()

Copy-Item (Join-Path $PSScriptRoot '..\db\migrations\001_junction_schema.sql') (Join-Path $OutDir '00_schema.sql') -Force

Write-CopyFile -CsvName 'tx_customers_junction.csv' -Table 'junction.cust' `
    -Columns 'customer_id', 'customer_postal_code', 'customer_age' `
    -OutFile (Join-Path $OutDir '01_cust.sql')

Write-CopyFile -CsvName 'tx_junction_transactions.csv' -Table 'junction.tx' `
    -Columns 'customer_id', 'bank_account_id', 'tx_date', 'tx_timestamp', 'category', 'tx_amount_eur',
             'balance_after_eur', 'transaction_type', 'merchant_id', 'mcc_code' `
    -TimestampIndex 3 -OutFile (Join-Path $OutDir '02_tx.sql')

Write-CopyFile -CsvName 'mtg_tx_customer_link_and_final_mtg_infio.csv' -Table 'junction.mtg_link' `
    -Columns 'mortgage_customer_id', 'customer_id', 'final_decision', 'rejection_reason', 'final_property_price_eur',
             'final_requested_loan_eur', 'final_equity_amount_eur', 'final_collateral_value_eur',
             'required_monthly_income_eur', 'final_loan_to_value' `
    -OutFile (Join-Path $OutDir '03_mtg_link.sql')

Write-CopyFile -CsvName 'mtg_negotiation_history.csv' -Table 'junction.mtg_events' `
    -Columns 'mortgage_customer_id', 'event_timestamp', 'event_type', 'property_id', 'property_type',
             'property_price_estimate', 'loan_amount', 'equity_amount', 'collateral_type', 'collateral_value',
             'collateral_status', 'decision', 'rejection_reason', 'expense_type', 'expense_amount', 'note' `
    -TimestampIndex 1 -OutFile (Join-Path $OutDir '04_mtg_events.sql')

$loadAll = @'
-- Generated by scripts/build-junction-sql.ps1. Run with:
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f db/seed/load_all.sql
-- Each COPY block commits on its own; re-running starts again from empty tables.
\set ON_ERROR_STOP on
\ir 00_schema.sql
TRUNCATE junction.mtg_events, junction.mtg_link, junction.tx, junction.cust RESTART IDENTITY;
\ir 01_cust.sql
\ir 02_tx.sql
\ir 03_mtg_link.sql
\ir 04_mtg_events.sql
ANALYZE junction.cust;
ANALYZE junction.tx;
ANALYZE junction.mtg_link;
ANALYZE junction.mtg_events;
'@
[System.IO.File]::WriteAllText((Join-Path $OutDir 'load_all.sql'), $loadAll.Replace("`r`n", "`n"), $utf8NoBom)

Write-Host ("Done in {0:N0}s. Load with: psql `"`$env:DATABASE_URL`" -v ON_ERROR_STOP=1 -f `"{1}`"" -f $sw.Elapsed.TotalSeconds, (Join-Path $OutDir 'load_all.sql'))
